import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true });
const url = process.env.UI_URL || 'http://127.0.0.1:5173';
const dxf = `0\nSECTION\n2\nHEADER\n9\n$INSUNITS\n70\n4\n0\nENDSEC\n0\nSECTION\n2\nENTITIES\n0\nLWPOLYLINE\n8\nWALL\n70\n1\n90\n4\n10\n0\n20\n0\n10\n4000\n20\n0\n10\n4000\n20\n200\n10\n0\n20\n200\n0\nENDSEC\n0\nEOF\n`;
const scroll = async (page, value) => { await page.evaluate(v => window.scrollTo(0, v), value); await page.waitForTimeout(180); };
try {
  for (const [width, height] of [[1440, 900], [1366, 768], [390, 844], [375, 667], [844, 390]]) {
    const page = await browser.newPage({ viewport: { width, height }, reducedMotion: 'reduce' });
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.goto(url, { waitUntil: 'networkidle' });
    assert.equal(await page.locator('html').getAttribute('lang'), 'vi');
    assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(250, 250, 250)');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.equal(await page.locator('#landing-error').isVisible(), false);
    const action = await page.locator('#landing-action button').boundingBox();
    assert.ok(action.y >= 0 && action.y + action.height <= height, 'upload fits viewport');
    await page.screenshot({ path: `/tmp/hephaestus-hero-${width}.png` });
    await scroll(page, height);
    assert.equal(await page.locator('body').getAttribute('data-chapter'), '1');
    await page.screenshot({ path: `/tmp/hephaestus-manifesto-${width}.png` });
    await scroll(page, height * 2);
    assert.equal(await page.locator('body').getAttribute('data-chapter'), '2');
    await page.screenshot({ path: `/tmp/hephaestus-works-${width}.png` });
    await page.getByRole('button', { name: 'Khám phá mẫu Một nếp nhà', exact: true }).click();
    assert.equal(await page.locator('#workspace').isVisible(), true);
    assert.equal(await page.locator('#project-name').innerText(), 'Một nếp nhà');
    assert.equal(await page.locator('#export-model').isEnabled(), true);
    assert.equal(await page.locator('#floor-select option').count(), 3);
    await page.getByRole('button', { name: 'Mặt bằng', exact: true }).click();
    assert.equal(await page.locator('[data-view="plan"]').getAttribute('aria-pressed'), 'true');
    await page.screenshot({ path: `/tmp/hephaestus-workspace-${width}.png` });
    if (width < 801) {
      await page.locator('[data-drawer="properties-panel"]').click();
      assert.equal(await page.locator('#properties-panel').isVisible(), true);
      await page.locator('#properties-panel [data-close-drawer]').click();
      await page.locator('[data-drawer="drawing-panel"]').click();
      assert.equal(await page.locator('#properties-panel').isVisible(), false);
      assert.equal(await page.locator('#drawing-panel').isVisible(), true);
      await page.keyboard.press('Escape');
    }
    await page.locator('#back-home').click();
    await scroll(page, height * 3);
    await page.waitForFunction(() => scrollY < 5);
    assert.equal(await page.locator('body').getAttribute('data-chapter'), '0');
    assert.equal(await page.locator('canvas').count(), 2);
    assert.deepEqual(errors, []);
    console.log(`PASS ${width}×${height}: chapters, wrap, sample, views, responsive drawers`);
    await page.close();
  }

  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(url, { waitUntil: 'networkidle' });
  await page.locator('#expand-preview').focus();
  await page.waitForTimeout(1100);
  const hero = await page.locator('#visual-frame').boundingBox();
  assert.ok(hero.width > 600);
  await scroll(page, 2400);
  const before = await page.locator('#visual-frame').boundingBox();
  await scroll(page, 2550);
  const after = await page.locator('#visual-frame').boundingBox();
  assert.notEqual(Math.round(before.x), Math.round(after.x));
  await scroll(page, 2400);
  const reversed = await page.locator('#visual-frame').boundingBox();
  assert.ok(Math.abs(before.x - reversed.x) < 2);
  await scroll(page, 2700);
  const wrapped = await page.locator('#visual-frame').boundingBox();
  assert.ok(Math.abs(hero.width - wrapped.width) < 2);
  console.log('PASS spring expansion, scroll morph reverse, seam, canvas reuse');
  await page.locator('[data-workspace]').click();
  await page.locator('#empty-sample').click();
  await page.locator('#component-select').selectOption({ index: 2 });
  await page.locator('#component-height').fill('0.5');
  await page.locator('#properties-form button').click();
  assert.equal(await page.locator('#component-height').inputValue(), '0.5');
  await page.locator('#undo').click();
  await page.locator('#component-select').selectOption({ index: 2 });
  assert.equal(await page.locator('#component-height').inputValue(), '0.22');
  await page.locator('#redo').click();
  await page.locator('#component-select').selectOption({ index: 2 });
  assert.equal(await page.locator('#component-height').inputValue(), '0.5');
  await page.locator('#section').fill('50');
  assert.equal(await page.locator('#section-value').innerText(), '50%');
  await page.locator('#file-input').setInputFiles({ name: 'wall.dxf', mimeType: 'application/dxf', buffer: Buffer.from(dxf) });
  await page.waitForFunction(() => !document.querySelector('#continue-build').disabled);
  assert.equal(await page.locator('#drawing-unit').inputValue(), 'mm');
  await page.locator('#continue-build').click();
  await page.waitForFunction(() => document.querySelector('#project-name').textContent === 'wall.dxf');
  assert.equal(await page.locator('#component-select option').count(), 2);
  await page.locator('#component-select').selectOption({ index: 1 });
  assert.match(await page.locator('#selection-info').innerText(), /4.00 × 0.20 × 3.20 m/);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export-model').click();
  const download = await downloadPromise;
  const binary = await readFile(await download.path());
  assert.equal(binary.subarray(0, 4).toString(), 'glTF');
  const jsonSize = binary.readUInt32LE(12);
  const gltf = JSON.parse(binary.subarray(20, 20 + jsonSize).toString());
  assert.ok(gltf.nodes.some(n => n.extras?.source?.includes('WALL')));
  await page.locator('#file-input').setInputFiles({ name: 'bad.dxf', mimeType: 'application/dxf', buffer: Buffer.from('invalid') });
  await page.waitForFunction(() => document.querySelector('#processing-status').textContent.includes('Không thể'));
  assert.equal(await page.locator('#project-name').innerText(), 'wall.dxf');
  assert.equal(await page.locator('#export-model').isEnabled(), true);
  await page.locator('#file-input').setInputFiles({ name: 'new.dxf', mimeType: 'application/dxf', buffer: Buffer.from(dxf) });
  await page.waitForFunction(() => !document.querySelector('#continue-build').disabled);
  const pendingPlan = await page.locator('#plan-svg').innerHTML();
  await page.locator('#component-select').selectOption({ index: 1 });
  await page.locator('#component-height').fill('4');
  await page.locator('#properties-form button').click();
  assert.equal(await page.locator('#file-name').innerText(), 'new.dxf');
  assert.equal(await page.locator('#plan-svg').innerHTML(), pendingPlan);
  await page.locator('#cancel-job').click();
  assert.equal(await page.locator('#continue-build').isEnabled(), false);
  assert.equal(await page.locator('#project-name').innerText(), 'wall.dxf');
  assert.deepEqual(errors, []);
  console.log('PASS source selection, parameter edits, undo/redo, sections, DXF worker, GLB contents, invalid replacement and cancel');
  await page.close();

  const fallback = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await fallback.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    HTMLCanvasElement.prototype.getContext = function(type, ...args) { return type.includes('webgl') ? null : original.call(this, type, ...args); };
  });
  await fallback.goto(url);
  await fallback.locator('#landing-error:not([hidden])').waitFor();
  assert.equal(await fallback.locator('h1').isVisible(), true);
  await fallback.locator('[data-workspace]').click();
  await fallback.locator('#empty-sample').click();
  assert.equal(await fallback.locator('#workspace-error').isVisible(), true);
  assert.equal(await fallback.locator('#plan-svg').isVisible(), true);
  assert.equal(await fallback.locator('#export-model').isEnabled(), false);
  console.log('PASS WebGL fallback retains source plan and upload');
} finally { await browser.close(); }

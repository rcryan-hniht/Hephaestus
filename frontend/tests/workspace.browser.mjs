import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

// Run against Vite proxying a test backend without OpenRouter credentials.
const browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
page.setDefaultTimeout(15000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:4174');
  await page.locator('[data-upload]').first().click();
  const accepted = page.waitForResponse(r => r.url().endsWith('/api/jobs') && r.status() === 202);
  await page.locator('#file-input').setInputFiles(new URL('../../backend/tests/fixtures/known_rooms.svg', import.meta.url).pathname);
  const job = await (await accepted).json();
  await page.locator('#api-questions').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#drawing-image').isVisible(), true);
  for (const [key, value] of Object.entries({ meters_per_unit: '.01', floor_height: '3', slab_thickness: '.2', door_height: '2.1', window_height: '1.2', window_sill: '.9' })) {
    await page.locator(`#question-${key}`).fill(value);
  }
  await page.locator('#api-questions button[type=submit]').click();
  await page.waitForFunction(() => document.getElementById('processing-status').textContent.startsWith('Ready ·'));
  assert.equal(await page.locator('#api-questions').isVisible(), false);
  assert.equal(await page.locator('#drawing-image').isVisible(), true);
  assert.equal(await page.locator('#export-model').isEnabled(), true);
  const sceneResponse = await page.request.get(`${new URL(page.url()).origin}/api/jobs/${job.id}/scene`);
  const original = await sceneResponse.json();
  const wall = original.components.find(c => c.type === 'wall');
  await page.locator('#component-select').selectOption(wall.id);
  await page.locator('#component-height').fill('3.5');
  await page.locator('#component-x').fill('.1');
  await page.locator('#properties-form button').click();
  await page.waitForFunction(() => document.getElementById('model-label').textContent.includes('REVISION 2'));
  const corrected = await (await page.request.get(`${new URL(page.url()).origin}/api/jobs/${job.id}/scene`)).json();
  const edited = corrected.components.find(c => c.id === wall.id);
  assert.equal(edited.height, 3.5);
  assert.ok(Math.abs(edited.polygon[0][0] - wall.polygon[0][0] - .1) < 1e-8);
  await page.locator('#undo').click();
  await page.waitForFunction(() => document.getElementById('model-label').textContent.includes('REVISION 1'));
  await page.locator('#redo').click();
  await page.waitForFunction(() => document.getElementById('model-label').textContent.includes('REVISION 2'));
  const download = page.waitForEvent('download');
  await page.locator('#export-scene').click();
  const saved = await download;
  const exported = JSON.parse(await readFile(await saved.path(), 'utf8'));
  assert.equal(exported.job_id, job.id);
  assert.equal(exported.revision, 2);
  const glbDownload = page.waitForEvent('download');
  await page.locator('#export-model').click();
  const binary = await readFile(await (await glbDownload).path());
  assert.equal(binary.readUInt32LE(0), 0x46546c67);
  const gltf = JSON.parse(binary.subarray(20, 20 + binary.readUInt32LE(12)).toString());
  assert.equal(gltf.nodes.find(n => n.extras?.job_id)?.extras.source_hash, job.source_hash);
  const door = corrected.components.find(c => c.type === 'door');
  await page.locator('#component-select').selectOption(door.id);
  await page.locator('#component-height').fill('5');
  await page.locator('#properties-form button').click();
  await page.waitForFunction(() => document.getElementById('processing-status').textContent.includes('Failed'));
  assert.equal(await page.locator('#properties-form button').isEnabled(), true);
  await page.locator('#component-height').fill('2.1');
  await page.locator('#properties-form button').click();
  await page.waitForFunction(() => document.getElementById('model-label').textContent.includes('REVISION 3'));
  await page.locator('#file-input').setInputFiles({ name: 'crossed.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg viewBox="0 0 100 100"><g class="Wall"><polygon points="0,0 50,50 0,50 50,0"/></g></svg>') });
  await page.waitForFunction(() => document.getElementById('processing-status').textContent.includes('Failed'));
  assert.equal(await page.locator('#drawing-image').isVisible(), true);
  const png = await page.evaluate(() => { const c = document.createElement('canvas'); c.width = 20; c.height = 10; return c.toDataURL().split(',')[1]; });
  await page.locator('#file-input').setInputFiles({ name: 'failed.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') });
  await page.waitForFunction(() => document.getElementById('processing-status').textContent.includes('Failed'));
  assert.match(await page.locator('#drawing-message').textContent(), /OPENROUTER_API_KEY|credential/i);
  assert.equal(await page.locator('#drawing-image').isVisible(), true);
  assert.equal(await page.locator('#export-model').isEnabled(), true);
  await page.locator('#component-select').selectOption(wall.id);
  assert.equal(await page.locator('#properties-form button').isDisabled(), true);
  assert.match(await page.locator('#model-label').textContent(), /REVISION 3/);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.locator('[data-drawer=drawing-panel]').click();
  assert.equal(await page.locator('#drawing-image').isVisible(), true);
  assert.deepEqual(errors, []);
  console.log('PASS: SVG reconstruction, corrections, history, GLB/JSON export, PNG failure retention, mobile layout');
} finally { await browser.close(); }

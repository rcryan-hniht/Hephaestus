import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1000 }, reducedMotion: 'reduce' });
  const failures = [], submissions = [];
  page.on('pageerror', error => failures.push(error.message));
  page.on('request', request => { if (request.method() === 'POST' && /\/api\/(jobs|buildings)$/.test(new URL(request.url()).pathname)) submissions.push(request.url()); });
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:4176');
  await page.locator('#explore-demo').click();
  assert.equal(await page.locator('#project-name').textContent(), 'Courtyard Residence', 'Keep the existing landing demo until a design is chosen');
  for (const [id,name] of [['terrace','Terrace Villa'], ['portal','Portal Villa'], ['gable','Gable Villa']]) {
    await page.locator('#demo-preset').selectOption(id);
    assert.ok((await page.locator('#preset-description').textContent()).includes('m building'));
    await page.locator('#preview-preset').click();
    assert.equal(await page.locator('#project-name').textContent(), name);
    assert.match(await page.locator('#model-label').textContent(), /DESIGN PRESET/);
    assert.equal(await page.locator('#export-model').isEnabled(), true);
    assert.equal(await page.locator('#drawing-settings').isVisible(), false);
    await page.waitForTimeout(350);
    await page.screenshot({ path: `/tmp/hephaestus-preset-${id}.png` });
    await page.locator('#export-model').click();
    const downloadPromise = page.waitForEvent('download');
    await page.locator('[data-export="glb"]').click();
    const download = await downloadPromise;
    const bytes = await readFile(await download.path());
    assert.equal(bytes.readUInt32LE(0), 0x46546c67);
    const gltf = JSON.parse(bytes.subarray(20,20+bytes.readUInt32LE(12)).toString());
    assert.ok(gltf.nodes.some(node => node.extras?.demoPreset === id && node.extras.sample === true));
    assert.ok(gltf.nodes.some(node => node.extras?.label?.startsWith('Step')));
    if (id === 'gable') assert.equal(gltf.nodes.filter(node => node.extras?.type === 'roof' && node.extras.profile).length, 2);
  }
  assert.equal(submissions.length, 0, 'Prepared presets must work without backend inference');
  await page.locator('#component-select').selectOption({ label: 'Left pitched roof · Floor 3' });
  assert.match(await page.locator('#selection-info').textContent(), /Approximate design dimensions/);
  assert.doesNotMatch(await page.locator('#selection-info').textContent(), /confirmed/i);
  await page.locator('#component-height').fill('3.6');
  await page.locator('#properties-form button').click();
  await page.locator('#component-select').selectOption({ label: 'Left pitched roof · Floor 3' });
  assert.equal(await page.locator('#component-height').inputValue(), '3.6');
  await page.locator('#undo').click();
  await page.locator('#component-select').selectOption({ label: 'Left pitched roof · Floor 3' });
  assert.equal(await page.locator('#component-height').inputValue(), '3.2');
  await page.locator('#redo').click();
  await page.locator('#component-select').selectOption({ label: 'Left pitched roof · Floor 3' });
  assert.equal(await page.locator('#component-height').inputValue(), '3.6');
  await page.locator('#load-sample').click();
  assert.equal(await page.locator('#project-name').textContent(), 'Courtyard Residence');
  assert.equal(await page.locator('#model-label').textContent(), 'DEMO MODEL · METRIC UNITS');
  const dxf = '0\nSECTION\n2\nHEADER\n9\n$INSUNITS\n70\n6\n0\nENDSEC\n0\nSECTION\n2\nENTITIES\n0\nLWPOLYLINE\n8\nWALL\n70\n1\n90\n4\n10\n0\n20\n0\n10\n4\n20\n0\n10\n4\n20\n0.2\n10\n0\n20\n0.2\n0\nENDSEC\n0\nEOF\n';
  await page.locator('#file-input').setInputFiles({ name: 'wall.dxf', mimeType: 'application/dxf', buffer: Buffer.from(dxf) });
  await page.locator('#continue-build').click();
  await page.waitForFunction(() => document.getElementById('model-label').textContent.startsWith('PRELIMINARY DXF'));
  assert.equal(await page.locator('#project-name').textContent(), 'wall.dxf');
  assert.match(await page.locator('#model-label').textContent(), /PRELIMINARY DXF/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('[data-drawer="drawing-panel"]').click();
  await page.locator('#demo-preset').selectOption('gable');
  await page.locator('#preview-preset').click();
  assert.equal(await page.locator('#project-name').textContent(), 'Gable Villa');
  assert.equal(await page.locator('#drawing-panel').isVisible(), false);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  assert.deepEqual(failures, []);
  console.log('PASS: three selectable villas, GLB metadata/roof geometry, edits/undo/redo, original demo, DXF upload and mobile drawer');
} finally { await browser.close(); }

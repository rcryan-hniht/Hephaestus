import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ headless:true,args:['--enable-unsafe-swiftshader'] });
const page = await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'reduce'});
page.setDefaultTimeout(10000);
let release;
try {
 await page.goto(process.env.TEST_URL || 'http://127.0.0.1:4174');
 await page.locator('[data-upload]').first().click();
 const svg = await readFile(new URL('../../backend/tests/fixtures/known_rooms.svg',import.meta.url));
 const valid = number => ({name:`F${number}.svg`,mimeType:'image/svg+xml',buffer:svg});
 const rejected = page.waitForResponse(r=>r.url().endsWith('/api/buildings') && r.status()===422);
 await page.locator('#file-input').setInputFiles([valid(1),{name:'F2.svg',mimeType:'image/svg+xml',buffer:Buffer.from('<invalid>')}]);
 await rejected;
 await page.waitForFunction(()=>document.getElementById('building-summary').textContent.includes('Batch rejected'));
 assert.equal(await page.locator('#api-questions').isVisible(),false,'invalid batch cannot partially schedule inference');
 await page.locator('#source-floor').selectOption('2');
 assert.equal(await page.locator('#retry-job').isVisible(),true,'submission failure remains retryable after switching floor');
 assert.match(await page.locator('#floor-status-2').textContent(),/failed/i);
 assert.match(await page.locator('#processing-status').textContent(),/failed/i);
 await page.locator('#file-input').setInputFiles([valid(1),valid(2)]);
 await page.locator('#api-questions').waitFor({state:'visible'});
 await page.locator('#question-meters_per_unit').fill('.02');
 await page.locator('#source-floor').selectOption('2');
 await page.locator('#api-questions').waitFor({state:'visible'});
 assert.equal(await page.locator('#question-meters_per_unit').inputValue(),'','drafts stay bound to their floor');
 await page.locator('#source-floor').selectOption('1');
 assert.equal(await page.locator('#question-meters_per_unit').inputValue(),'.02','draft survives switching');
 const gate = new Promise(resolve => { release=resolve; });
 await page.route('**/api/jobs/*/answers', async route => { await gate; await route.continue(); });
 const request = page.waitForRequest(r=>r.url().endsWith('/answers'));
 await page.getByRole('button',{name:'Use all suggestions',exact:true}).click(); await request;
 assert.equal(await page.locator('#source-floor').isDisabled(),true,'cannot switch source during a correction');
 release();
 await page.waitForFunction(()=>document.getElementById('question-door_height')?.value === '2.1');
 await page.unroute('**/api/jobs/*/answers');
 await page.locator('#cancel-job').click();
 await page.waitForFunction(()=>document.getElementById('processing-status').textContent.includes('Cancelled'));
 assert.equal(await page.locator('#drawing-image').isVisible(),true);
 await page.locator('#retry-job').click();
 await page.locator('#api-questions').waitFor({state:'visible'});
 assert.equal(await page.locator('#source-floor').inputValue(),'1');
 console.log('PASS: per-floor submission errors, independent drafts, busy source lock and cancel/retry');
} finally { release?.(); await browser.close(); }
